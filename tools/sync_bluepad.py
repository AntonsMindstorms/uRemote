"""Copy library/uremote.py into library/bluepad_ur.py.

bluepad_ur.py must work as ONE uploaded file on a Pybricks hub, but the
uRemote client must have a single source of truth: library/uremote.py.
This script splices uremote.py (everything from ``import __main__`` onward,
so the module header and ``__version__`` of bluepad_ur.py stay its own)
between the ``# >>> uremote.py`` and ``# <<< uremote.py`` markers.

    python tools/sync_bluepad.py          rewrite bluepad_ur.py
    python tools/sync_bluepad.py --check  exit 1 if bluepad_ur.py is stale
"""

import sys
from pathlib import Path

LIB = Path(__file__).resolve().parents[1] / "library"
START = "# >>> uremote.py (generated by tools/sync_bluepad.py, do not edit by hand)\n"
END = "# <<< uremote.py\n"


def build():
    """Return the up-to-date text of bluepad_ur.py."""
    uremote = (LIB / "uremote.py").read_text()
    body = uremote[uremote.index("import __main__"):]
    bluepad = (LIB / "bluepad_ur.py").read_text()
    head, rest = bluepad.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + START + body.rstrip("\n") + "\n" + END + tail


if __name__ == "__main__":
    new = build()
    target = LIB / "bluepad_ur.py"
    if "--check" in sys.argv:
        if new != target.read_text():
            sys.exit("bluepad_ur.py is out of date with uremote.py. Run: python tools/sync_bluepad.py")
    else:
        target.write_text(new)
